"""Engle-Granger pairwise cointegration screen (FRD Section 8.2).

Uses statsmodels.tsa.stattools.coint, which runs the two-step EG procedure and reports
MacKinnon's Engle-Granger/Phillips-Ouliaris p-values -- NOT plain Dickey-Fuller critical
values. That distinction matters: an EG residual series' critical values differ from a
standard ADF's because the residual was itself generated by an estimated regression; coint()
already accounts for this.

Deliberately run in BOTH regressand directions for every pair (run_engle_granger_both_directions)
-- EG results are not invariant to which series is treated as the regressand (the FRD calls
this out explicitly), so reporting only one direction would hide that sensitivity rather than
surface it.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np
from statsmodels.tsa.stattools import coint

from pipeline.cointegration.half_life import estimate_half_life

# Conventional cutoff for reading the EG test's own p-value (diagnostic interpretation of this
# one statistic) -- NOT a Phase 3 trading/health gate.
EG_SIGNIFICANCE = 0.05


@dataclass(frozen=True)
class EngleGrangerResult:
    regressand_symbol: str
    regressor_symbol: str
    test_statistic: float
    p_value: float
    hedge_ratio: float
    half_life_days: float | None
    is_significant_5pct: bool


def run_engle_granger(regressand, regressor, regressand_symbol: str, regressor_symbol: str) -> EngleGrangerResult:
    regressand = np.asarray(regressand, dtype=float)
    regressor = np.asarray(regressor, dtype=float)

    test_stat, p_value, _crit_values = coint(regressand, regressor, trend="c", autolag="AIC")

    design = np.column_stack([np.ones_like(regressor), regressor])
    beta_hat, *_ = np.linalg.lstsq(design, regressand, rcond=None)
    hedge_ratio = float(beta_hat[1])

    spread = regressand - hedge_ratio * regressor
    half_life = estimate_half_life(spread)

    return EngleGrangerResult(
        regressand_symbol=regressand_symbol,
        regressor_symbol=regressor_symbol,
        test_statistic=float(test_stat),
        p_value=float(p_value),
        hedge_ratio=hedge_ratio,
        half_life_days=half_life,
        is_significant_5pct=bool(p_value < EG_SIGNIFICANCE),
    )


def run_engle_granger_both_directions(
    symbol_a: str, series_a, symbol_b: str, series_b
) -> tuple[EngleGrangerResult, EngleGrangerResult]:
    forward = run_engle_granger(series_a, series_b, symbol_a, symbol_b)
    reverse = run_engle_granger(series_b, series_a, symbol_b, symbol_a)
    return forward, reverse
